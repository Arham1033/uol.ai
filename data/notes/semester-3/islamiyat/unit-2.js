const inD = (s) => D[s] || NM[s];
const art = (s) => s.startsWith("ال");
const caseFor = (s, c) => (NM[s] && !D[s] && c === "i" ? "a" : c);
const noun = (s, c) => end(s, caseFor(s, c));
const KIND = {
  inna: { c: "a", ar: (s) => `إِنَّ ${noun(s, "a")}`, ur: (u) => `بے شک ${u}` },
  li: { c: "i", ar: () => "", ur: (u) => `${u} کے لیے` },
  fi: { c: "i", ar: (s) => `فِي ${noun(s, "i")}`, ur: (u) => `${u} میں` },
  ala: { c: "i", ar: (s) => `عَلَى ${noun(s, "i")}`, ur: (u) => `${u} پر` },
  min: { c: "i", ar: (s) => (art(s) ? "مِنَ " : "مِنْ ") + noun(s, "i"), ur: (u) => `${u} سے` },
  ila: { c: "i", ar: (s) => `إِلَى ${noun(s, "i")}`, ur: (u) => `${u} کی طرف` },
  bi: { c: "i", ar: (s) => "بِ" + noun(s, "i"), ur: (u) => `${u} سے / پر / کو` },
  wa: { c: "i", ar: (s) => "وَ" + noun(s, "i"), ur: (u) => `قسم ہے ${u} کی` },
};
const liPhrase = (s) => {
  if (s === "اللَّه") return "لِلَّهِ";
  return "لِ" + (art(s) ? s.slice(1) : s) + (hasEnd(s) ? "" : MARK[caseFor(s, "i")]);
};
const row = (kind, s) => [kind === "li" ? liPhrase(s) : KIND[kind].ar(s), KIND[kind].ur(inD(s))];
const rows = (kind, list) => list.map((s) => row(kind, s));
// Words without (اَلْ): "a / one" is added to the meaning.
const iRow = (kind, s, mid = "کسی") => {
  const u = `${mid} ${I[s]}`;
  const ar =
    kind === "li" ? "لِ" + tan(s)
    : kind === "fi" ? "فِي " + tan(s)
    : kind === "ala" ? "عَلَى " + tan(s)
    : kind === "min" ? "مِنْ " + tan(s)
    : kind === "ila" ? "إِلَى " + tan(s)
    : "بِ" + tan(s);
  return [ar, KIND[kind].ur(u)];
};
const iRows = (kind, list, mid) => list.map((s) => iRow(kind, s, mid));
// Words joined with (وَ): "A and B".
const andRows = (kind, list) =>
  list.map(([a, b]) => {
    const first = row(kind, a);
    const secondAr = art(b) ? "وَ" + noun(b, KIND[kind].c) : "وَ" + noun(b, KIND[kind].c);
    const ur = KIND[kind].ur(`${inD(a)} اور ${inD(b)}`);
    return [first[0] + " " + secondAr, ur];
  });


