const pairs = (rows) => ({ type: "pairs", rtl: true, rows });
const heading = (text) => ({ type: "heading", text, rtl: true });
const sub = (text) => ({ type: "subheading", text, rtl: true });
const rule = (text, title = "قاعدہ") => ({ type: "callout", variant: "tip", title, text, rtl: true });
const note = (text, title = "نوٹ") => ({ type: "callout", variant: "note", title, text, rtl: true });

// Write rows as lines: "arabic = urdu". Blank lines are ignored.
const L = (text) =>
  text
    .split("\n")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const i = s.indexOf("=");
      return [s.slice(0, i).trim(), s.slice(i + 1).trim()];
    });
const P = (text) => pairs(L(text));

// Idafa: [first word with its Urdu and the Urdu link word] + second word.
// first = [arabic (nominative, no tanwin), urdu, link]; second = [arabic (genitive), urdu]
